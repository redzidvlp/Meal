// Builds the SQL that ships to users from the readable source files.
//
//   supabase/migrations/*.sql              → applied by the Supabase GitHub integration
//   supabase/upgrade-existing-project.sql  → one paste for the SQL editor
//
//   npm run build:sql
//
// The legacy block below is the same text in every output, so an old project is
// upgraded identically whether the integration runs it or a person pastes it.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = file => readFileSync(join(root, "supabase", file), "utf8");
const migrationsDir = join(root, "supabase", "migrations");
mkdirSync(migrationsDir, { recursive: true });

const schema = read("schema.sql");
const seed = read("seed.sql");
const migrate = read("migrate-legacy-data.sql");
const doctor = read("doctor.sql");

// Idempotent: on a fresh project nothing matches, on a new schema the sentinel
// table is already there so it never touches the new tables.
const LEGACY_MOVE = `-- Step 1 — step the old "Our Meal Plan" tables aside.
-- Nothing is deleted: they are moved into a \`legacy\` schema so the new tables can
-- be created with the same names. No-op on a fresh project or a second run.
do $$
declare
  t text;
begin
  if to_regclass('public.meal_assignments') is null then
    create schema if not exists legacy;
    foreach t in array array[
      'plan', 'meal_swaps', 'recipe_notes', 'eaten', 'water', 'profiles', 'households',
      'recipes', 'meal_assignments', 'shopping_checks', 'pantry', 'menus', 'day_sections', 'labels'
    ] loop
      if exists (
        select 1 from information_schema.tables where table_schema = 'public' and table_name = t
      ) and not exists (
        select 1 from information_schema.tables where table_schema = 'legacy' and table_name = t
      ) then
        execute format('alter table public.%I set schema legacy', t);
        raise notice 'moved public.% to legacy.%', t, t;
      end if;
    end loop;
  end if;
end $$;

-- The old helpers have the same arguments but a different return type, which
-- blocks CREATE OR REPLACE. schema.sql recreates them.
drop function if exists public.create_household(text, text, text);
drop function if exists public.join_household(text, text, text);
`;

const standaloneLegacy = `-- Our Table — isolate the schema of the previous "Our Meal Plan" app
--
-- The old app used public.plan, public.meal_swaps and narrower versions of
-- public.eaten / water / recipe_notes / profiles / households. Running
-- schema.sql next to them would silently keep the old columns, so the new app
-- would open but fail when writing (for example eaten.recipe_id is missing).
--
-- This script does not delete anything. It moves those tables into a \`legacy\`
-- schema, so \`schema.sql\` can build clean tables with the same names in
-- \`public\`. Auth accounts stay in auth.users and keep working; the data itself
-- is carried over by migrate-legacy-data.sql.
--
-- Most people only need the one-paste file: supabase/upgrade-existing-project.sql
--
-- Re-running is safe: a second run finds nothing to move and only drops the two
-- old helper functions so schema.sql can recreate them.

${LEGACY_MOVE}`;

writeFileSync(join(root, "supabase", "upgrade-from-legacy.sql"), standaloneLegacy);

const combined = `-- ═══════════════════════════════════════════════════════════════════════════
-- Our Table — upgrade the EXISTING Supabase project (one paste)
--
-- Generated by scripts/build-sql.mjs — edit the source files, not this one.
--
-- Use this when the project already holds your old "Our Meal Plan" data and you
-- want the same logins, the same household and the same person names.
--
-- How to run it
--   1. Supabase → SQL Editor → New query
--   2. Paste this whole file → Run
--   3. Read the last result: every table must say "ok" (that is doctor.sql)
--
-- It is safe to run twice:
--   • old tables are moved to the \`legacy\` schema once (nothing deleted)
--   • tables, policies and functions are created only if missing
--   • the recipe library is inserted/updated by id
--   • household, profiles, plan, eaten, water and notes are copied only when absent
-- ═══════════════════════════════════════════════════════════════════════════

${LEGACY_MOVE}

-- Step 2 — create the new schema (tables, RLS, RPCs, realtime)
${schema}

-- Step 3 — the preset recipe + day-menu library
${seed}

-- Step 4 — carry the old household, logins, week, water and notes across
${migrate.replace(/^begin;\s*$/m, "").replace(/^commit;\s*$/m, "")}

-- Step 5 — health check: every table must read "ok"
${doctor}
`;

writeFileSync(join(root, "supabase", "upgrade-existing-project.sql"), combined);

// Migrations: the integration applies these to the production branch.
const schemaMigration = `-- Generated by scripts/build-sql.mjs — edit supabase/schema.sql instead.
-- Our Table — database schema

${LEGACY_MOVE}
${schema}`;
const seedMigration = `-- Generated by scripts/build-sql.mjs — edit supabase/seed.sql instead.

${seed}`;

writeFileSync(join(migrationsDir, "20261020120000_our_table_schema.sql"), schemaMigration);
writeFileSync(join(migrationsDir, "20261020120100_our_table_seed.sql"), seedMigration);

const kb = text => `${Math.round(Buffer.byteLength(text) / 1024)} kB`;
console.log(`supabase/migrations/20261020120000_our_table_schema.sql  ${kb(schemaMigration)}`);
console.log(`supabase/migrations/20261020120100_our_table_seed.sql    ${kb(seedMigration)}`);
console.log(`supabase/upgrade-existing-project.sql                    ${kb(combined)}`);
console.log(`supabase/upgrade-from-legacy.sql                         ${kb(standaloneLegacy)}`);
