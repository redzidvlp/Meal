// Generates supabase/seed.sql from the reviewed preset library.
// Run: npm run seed:sql
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { PRESET_RECIPES } from "../src/data/presets.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const sqlString = value => `'${String(value ?? "").replace(/'/g, "''")}'`;
const num = value => (Math.round(Number(value) * 10) / 10).toString();

const rows = PRESET_RECIPES.map(recipe => {
  const tags = `array[${(recipe.tags || ["vegetarian"]).map(sqlString).join(", ")}]::text[]`;
  return `(
  ${sqlString(recipe.id)},
  null,
  ${sqlString(recipe.name.en)},
  ${sqlString(recipe.name.lt)},
  ${sqlString(recipe.emoji)},
  ${sqlString(recipe.slot)},
  ${Math.round(recipe.kcal)},
  ${num(recipe.protein)},
  ${num(recipe.carbs)},
  ${num(recipe.fat)},
  ${sqlString(JSON.stringify(recipe.ingredients))}::jsonb,
  ${sqlString(recipe.method.en)},
  ${sqlString(recipe.method.lt)},
  ${tags},
  true,
  ${Math.round(recipe.prepMinutes || 15)}
)`;
}).join(",\n");

const sql = `-- ═══════════════════════════════════════════════════════════════════════════
-- Our Table — shared vegetarian recipe library (generated)
-- Generated by scripts/generate-seed.mjs — do not edit by hand.
-- These rows have household_id = NULL and are read-only in the app.
-- ═══════════════════════════════════════════════════════════════════════════

insert into public.recipes (
  id, household_id, name_en, name_lt, emoji, slot, kcal, protein, carbs, fat,
  ingredients, method_en, method_lt, tags, vegetarian, prep_minutes
) values
${rows}
on conflict (id) do update set
  name_en = excluded.name_en,
  name_lt = excluded.name_lt,
  emoji = excluded.emoji,
  slot = excluded.slot,
  kcal = excluded.kcal,
  protein = excluded.protein,
  carbs = excluded.carbs,
  fat = excluded.fat,
  ingredients = excluded.ingredients,
  method_en = excluded.method_en,
  method_lt = excluded.method_lt,
  tags = excluded.tags,
  prep_minutes = excluded.prep_minutes,
  updated_at = now()
where recipes.household_id is null;
`;

writeFileSync(join(root, "supabase", "seed.sql"), sql, "utf8");
console.log(`Wrote supabase/seed.sql with ${PRESET_RECIPES.length} recipes.`);
